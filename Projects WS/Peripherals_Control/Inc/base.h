#ifndef BASE_H_
#define BASE_H_

// BASE ADDRESS
#define PERIPHERALS_BASE  (0x40000000)

// BUSES OFFSETS
#define AHB1_PERI_OFFSET  (0x00020000) // For RCC, GPIOA, GPIOB, GPIOC
#define APB1_PERI_OFFSET  (0x00000000) // For UART
#define APB2_PERI_OFFSET  (0x00010000) // For ADC

// BUSES BASES
#define AHB1_PERI_BASE    (PERIPHERALS_BASE + AHB1_PERI_OFFSET)
#define APB1_PERI_BASE    (PERIPHERALS_BASE + APB1_PERI_OFFSET)
#define APB2_PERI_BASE    (PERIPHERALS_BASE + APB2_PERI_OFFSET)

// PERIPHERALS OFFSETS
#define RCC_PERI_OFFSET   (0x00003800)
#define GPIOA_PERI_OFFSET (0x00000000)
#define GPIOB_PERI_OFFSET (0x00000400)
#define GPIOC_PERI_OFFSET (0x00000800)
#define UART_PERI_OFFSET  (0x00004400)
#define ADC_PERI_OFFSET   (0x00002000)

// PERIPHERALS BASES
#define RCC_PERI_BASE     (AHB1_PERI_BASE + RCC_PERI_OFFSET)
#define GPIOA_PERI_BASE   (AHB1_PERI_BASE + GPIOA_PERI_OFFSET)
#define GPIOB_PERI_BASE   (AHB1_PERI_BASE + GPIOB_PERI_OFFSET)
#define GPIOC_PERI_BASE   (AHB1_PERI_BASE + GPIOC_PERI_OFFSET)
#define UART_PERI_BASE    (APB1_PERI_BASE + UART_PERI_OFFSET)
#define ADC_PERI_BASE     (APB2_PERI_BASE + ADC_PERI_OFFSET)

enum State {
	OFF = 48,
	ON  = 49
};

#endif // BASE_H_
